def part_role(pd) -> str:
    """The 'Role:' paragraph of the part module's docstring, as one line."""
    import sys as _sys
    doc = _sys.modules[pd.make.__module__].__doc__ or ""
    if "Role:" not in doc:
        return ""
    text = doc.split("Role:", 1)[1].split("\n\n", 1)[0]
    return " ".join(text.split())


