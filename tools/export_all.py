"""Regenerate everything that is derived from the CAD (PROJECT_SPEC 4.8, 12.2).

Role in the system
------------------
One command turns cad/params/arm_params.json + the part modules into:

  cad/export/stl/NN_name_Qx.stl     one STL per printed part
  cad/export/exxeta_arm.step        STEP of the whole assembly
  cad/export/masses.json            mass and centre of mass of every part
  description/exxeta_arm.urdf       robot description + link meshes
  docs/img/*.png                    renders for the docs
  docs/design/cad_checks.md         results of the automatic checks
  docs/design/torque_budget.md      torque budget on the REAL part masses

and runs three checks that must pass:

  1. print-bed fit      every part fits the configured printer
  2. interference       no two parts overlap anywhere in the joint ranges
  3. SIZING GATE        every joint keeps its safety factor with the CAD masses.
                        If this fails the script stops with exit code 1 and the
                        design must go back to the owner (ADR-0001).

Run (from the project root, inside the project venv):
    python tools/export_all.py                 everything
    python tools/export_all.py --fast          skip interference check and renders
"""
from __future__ import annotations

