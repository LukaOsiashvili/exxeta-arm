def _overlap(a, b):
    ba, bb = a.bounding_box(), b.bounding_box()
    if (ba.max.X < bb.min.X or bb.max.X < ba.min.X or ba.max.Y < bb.min.Y or bb.max.Y < ba.min.Y
            or ba.max.Z < bb.min.Z or bb.max.Z < ba.min.Z):
        return 0.0
    try:
        common = a & b
        return float(common.volume) if common is not None else 0.0
    except Exception:
        return 0.0


def check_interference(solids):
    """solids: {link: [(label, solid in link frame)]}. Returns list of (pose, a, b, volume)."""
    problems = []
    seen = set()

    def test(pose_name, q, pairs_of_links):
        frames = assembly.link_frames(q)
        world = {link: [(lab, frames[link] * s) for lab, s in solids[link]] for link in solids}
        for la, lb in pairs_of_links:
            for na, sa in world[la]:
                for nb, sb in world[lb]:
                    if la == lb and na >= nb:
                        continue
                    v = _overlap(sa, sb)
                    if v > MIN_OVERLAP_MM3 and (pose_name, na, nb) not in seen:
                        seen.add((pose_name, na, nb))
                        problems.append((pose_name, f"{la}/{na}", f"{lb}/{nb}", round(v, 1)))

    links = list(solids)
    # 1. static fit: parts that share a link must not overlap (servo in its pocket, pin in its hole ...)
    test("static", assembly.POSES["zero"], [(k, k) for k in links])
    # 2. named poses: every pair of different links
    all_pairs = [(a, b) for i, a in enumerate(links) for b in links[i + 1:]]
    for name in ("zero", "home", "reach", "rest"):
        test(name, assembly.POSES[name], all_pairs)
        log(f"interference: pose {name} done ({len(problems)} problems so far)")
    # 3. sweep every joint over its range, checking the two links it connects
    home = list(assembly.POSES["home"])
    for jid, la, lb in JOINT_LINKS:
        idx = int(jid[1]) - 1
        lo, hi = RAW["joints"][jid]["min_deg"], RAW["joints"][jid]["max_deg"]
        for k in range(5):
            q = list(home)
            q[idx] = lo + (hi - lo) * k / 4
            test(f"{jid}={q[idx]:.0f}", q, [(la, lb)])
        log(f"interference: sweep {jid} done ({len(problems)} problems so far)")
    return problems


