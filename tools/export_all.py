def export_link_steps(link_solids, printed_names):
    """cad/export/fusion_links/: one STEP per link (exact geometry, link frame) for the Fusion 360 script."""
    import json as _json

    from build123d import Rot
    out = EXPORT / "fusion_links"
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("*.step"):
        old.unlink()
    frames = assembly.link_frames(assembly.POSES["zero"])
    index = {}
    for link, items in link_solids.items():
        # finger_b is finger_a turned 180 degrees about the hand axis: bake that into the geometry,
        # so every link frame is a pure translation of the world frame in the zero pose
        fix = Rot(0, 0, 180) if link == "finger_b" else None
        origin = frames["gripper" if link in ("pinion", "finger_a", "finger_b") else link].position
        entry = {"origin_mm": [round(origin.X, 4), round(origin.Y, 4), round(origin.Z, 4)], "files": []}
        for kind in ("printed", "bought"):
            solids = [(fix * s if fix else s) for n, s in items if (n in printed_names) == (kind == "printed")]
            if solids:
                fname = f"{link}_{kind}.step"
                export_step(Compound(solids), str(out / fname))
                entry["files"].append(fname)
        index[link] = entry
    (out / "index.json").write_text(_json.dumps(index, indent=2), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description="Regenerate all CAD-derived outputs and run the checks.")
    ap.add_argument("--fast", action="store_true", help="skip the interference check and the renders")
    args = ap.parse_args()
    t0 = time.time()

    built = export_parts()
    bed_ok, bed_rows = check_bed(built)
    log(f"bed fit: {'PASS' if bed_ok else 'FAIL'}")
    write_masses(built)
    gate_ok, gate_text = sizing_gate()
    log("sizing gate: " + ("PASS" if gate_ok else "FAIL") + "\n" + gate_text)

    # link solids (printed + bought parts) are reused for URDF, STEP and interference
    link_solids = {k: [] for k in assembly.link_frames(assembly.POSES["zero"])}
    for pd, link, loc in assembly.part_instances():
        link_solids[link].append((pd.name, loc * built[pd.name][1]))
    printed_mass = {k: sum(mass_g(s) for _, s in v) for k, v in link_solids.items()}
    for name, link, solid in assembly.vendor_instances():
        link_solids[link].append((name, solid))

    urdf_solids = {k: [s for _, s in v] for k, v in link_solids.items()}
    log(f"URDF: {gen_urdf.generate(urdf_solids, printed_mass)}")

    frames = assembly.link_frames(assembly.POSES["home"])
    world = [frames[link] * s for link, v in link_solids.items() for _, s in v]
    export_step(Compound(world), str(EXPORT / "exxeta_arm.step"))
    export_link_steps(link_solids, set(built))
    log("STEP assembly and per-link STEP files written")

    problems = []
    if not args.fast:
        problems = check_interference(link_solids)
        make_renders(built)
    write_report(built, bed_rows, bed_ok, problems, gate_ok, gate_text, args.fast)
    write_print_guide(built)
    write_parts_list(built)
    log(f"report: {REPORT.relative_to(ROOT)}   total {time.time() - t0:.0f} s")

    if not gate_ok:
        log("SIZING GATE FAILED. Stop here and tell the owner (ADR-0001).")
        sys.exit(1)
    if not bed_ok or problems:
        log("CHECKS FAILED: see docs/design/cad_checks.md")
        sys.exit(2)
    log("ALL CHECKS PASSED")


if __name__ == "__main__":
    main()
