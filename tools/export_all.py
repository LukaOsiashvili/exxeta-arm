def make_renders(built):
    IMG.mkdir(parents=True, exist_ok=True)
    views = [("assembly_home", "home", -60, 20), ("assembly_home_front", "home", 35, 25),
             ("assembly_rest", "rest", -60, 20), ("assembly_reach", "reach", -75, 15), ("assembly_zero", "zero", -60, 15)]
    for fname, pose, az, el in views:
        meshes = []
        for label, kind, link, color, solid in assembly.build(assembly.POSES[pose]):
            v, t = tessellate(solid, 0.25, 0.5)
            meshes.append((v, t, COLORS[color]))
        render(meshes, IMG / f"{fname}.png", azimuth=az, elevation=el)
        log(f"render {fname}.png")
    for name, (pd, solid, _) in built.items():
        v, t = tessellate(solid, 0.15, 0.4)
        render([(v, t, COLORS[pd.color])], IMG / f"part_{pd.number:02d}_{name}.png", size=(700, 560), azimuth=-50, elevation=28)
    log("part renders done")


def write_report(built, bed_rows, bed_ok, problems, gate_ok, gate_text, skipped):
    L = ["# CAD checks", "",
         "> **Generated file.** Regenerate with `python tools/export_all.py`.",
         f"> Design revision `{P.project.design_revision}`.", "",
         "## Summary", "",
         f"- Print-bed fit ({P.printer.bed_mm[0]} x {P.printer.bed_mm[1]} x {P.printer.bed_mm[2]} mm): **{'PASS' if bed_ok else 'FAIL'}**",
         f"- Interference check: **{'skipped (--fast)' if skipped else ('PASS' if not problems else 'FAIL')}**",
         f"- Sizing gate (torque budget on CAD masses): **{'PASS' if gate_ok else 'FAIL'}**", "",
         "## Parts", "",
         "| # | File | Qty | Mass each (g) | Bounding box (mm) | Fits bed | Print orientation | Supports |",
         "|---|---|---|---|---|---|---|---|"]
    fit = {f: ok for f, _, ok in bed_rows}
    for name, (pd, _, info) in built.items():
        L.append(f"| {pd.number:02d} | `{pd.filename}` | {pd.qty} | {info['unit_mass_g']} | "
                 f"{info['bbox_mm'][0]} x {info['bbox_mm'][1]} x {info['bbox_mm'][2]} | {'yes' if fit[pd.filename] else 'NO'} | "
                 f"{pd.orientation} | {pd.supports} |")
    total = sum(i["unit_mass_g"] * pd.qty for pd, _, i in built.values() if not pd.optional)
    L += ["", f"Printed mass of the standard arm (no pots, no test parts): **{total:.0f} g** "
              f"(PETG, {P.mass_model.print.fill_factor * 100:.0f} % effective fill).", "",
          "## Interference", ""]
    if skipped:
        L.append("Not run.")
    elif not problems:
        L.append("No overlaps above "
                 f"{MIN_OVERLAP_MM3} mm³ in: static fit of all parts and servos, the poses zero / home / reach / rest, "
                 "and five samples across the range of every joint.")
    else:
        L += ["| Pose | Part A | Part B | Overlap (mm³) |", "|---|---|---|---|"]
        L += [f"| {p} | {a} | {b} | {v} |" for p, a, b, v in problems]
    L += ["", "## Sizing gate output", "", "```", gate_text.strip(), "```", ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(L), encoding="utf-8")


