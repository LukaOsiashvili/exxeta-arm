from parts import all_parts  # noqa: E402
from render import COLORS, render, tessellate  # noqa: E402

EXPORT = ROOT / "cad" / "export"
IMG = ROOT / "docs" / "img"
REPORT = ROOT / "docs" / "design" / "cad_checks.md"
BUDGET_LINK = {"upper_arm": "upper_arm", "forearm": "forearm", "wrist": "hand", "gripper": "hand",
               "pinion": "hand", "finger_a": "hand", "finger_b": "hand"}
# joints and the two links they connect (for the range-of-motion interference sweep)
JOINT_LINKS = [("J1", "base", "turntable"), ("J2", "turntable", "upper_arm"), ("J3", "upper_arm", "forearm"),
               ("J4", "forearm", "wrist"), ("J5", "wrist", "gripper"), ("J6", "gripper", "finger_a"),
               ("J6", "gripper", "finger_b"), ("J6", "pinion", "finger_a"), ("J6", "finger_a", "finger_b")]
MIN_OVERLAP_MM3 = 2.0     # smaller overlaps are touching faces / numerical noise


def log(msg):
    print(f"[export] {msg}", flush=True)


# --------------------------------------------------------------------------
def export_parts():
    """Build every part once, write its STL, return {name: (PartDef, solid, info)}."""
    (EXPORT / "stl").mkdir(parents=True, exist_ok=True)
    for old in (EXPORT / "stl").glob("*.stl"):
        old.unlink()
    built = {}
    for pd in all_parts():
        t = time.time()
        solid = pd.make()
        export_stl(solid, str(EXPORT / "stl" / pd.filename), tolerance=0.05, angular_tolerance=0.2)
        bb = solid.bounding_box()
        com = solid.center()
        info = {"number": pd.number, "file": pd.filename, "qty": pd.qty, "optional": pd.optional,
                "volume_cm3": round(solid.volume / 1000, 2), "unit_mass_g": round(mass_g(solid), 1),
                "bbox_mm": [round(bb.size.X, 1), round(bb.size.Y, 1), round(bb.size.Z, 1)],
                "com_mm": [round(com.X, 2), round(com.Y, 2), round(com.Z, 2)], "link": pd.link}
        built[pd.name] = (pd, solid, info)
        log(f"{pd.filename:32s} {info['unit_mass_g']:6.1f} g  bbox {info['bbox_mm']}  ({time.time() - t:.1f} s)")
    return built


def check_bed(built):
    bed = sorted(P.printer.bed_mm)
    rows, ok = [], True
    for name, (pd, _, info) in built.items():
        fits = all(a <= b for a, b in zip(sorted(info["bbox_mm"]), bed))
        ok &= fits
        rows.append((pd.filename, info["bbox_mm"], fits))
    return ok, rows


def write_masses(built):
    """cad/export/masses.json: the input of the torque budget (sizing gate)."""
    parts = {}
    count = {}
    for pd, link, _ in assembly.part_instances():
        count[pd.name] = count.get(pd.name, 0) + 1
    for name, (pd, solid, info) in built.items():
        n = count.get(name, 0)
        entry = {"unit_mass_g": info["unit_mass_g"], "qty_in_arm": n, "mass_g": round(info["unit_mass_g"] * max(n, 1), 1),
                 "cad_link": pd.link}
        if pd.link in BUDGET_LINK:
            entry["link"] = BUDGET_LINK[pd.link]
            entry["com_along_mm"] = info["com_mm"][2]   # link frames have +Z along the link
        parts[name] = entry
    data = {"_about": "GENERATED by tools/export_all.py. Printed-part masses = CAD volume x density x fill factor.",
            "design_revision": P.project.design_revision,
            "density_g_cm3": P.mass_model.print.density_g_cm3, "fill_factor": P.mass_model.print.fill_factor,
            "parts": parts}
    (EXPORT / "masses.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    return data


def sizing_gate():
    """Rerun the torque budget on the CAD masses. Returns (ok, output text)."""
    r = subprocess.run([sys.executable, str(ROOT / "tools" / "torque_budget.py"), "--gate"], capture_output=True, text=True)
    subprocess.run([sys.executable, str(ROOT / "tools" / "power_budget.py")], capture_output=True, text=True)
    return r.returncode == 0, r.stdout + r.stderr


