"""Generate description/exxeta_arm.urdf and the link meshes from the CAD.

Role in the system
------------------
The URDF is the robot description shared by the kinematics node, the simulator
and the 3D view in the web app. It is GENERATED from arm_params.json and the CAD
(never edit it by hand): change a link length in the params, run
tools/export_all.py, and every consumer sees the new geometry.

Frames are exactly those of cad/assembly.py. URDF uses metres and radians.

Gripper: the firmware commands the J6 SERVO ANGLE. In the URDF the two fingers
are prismatic joints: `gripper` (finger_a) and `gripper_mimic` (finger_b, mimics
it). Finger travel in metres = servo angle in radians x pinion radius; the
factor is stored in description/robot_info.json for the software.

Called by tools/export_all.py; can also be run alone:  python tools/gen_urdf.py
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "cad"))
sys.path.insert(0, str(ROOT / "tools"))

from build123d import Compound, export_stl  # noqa: E402

import assembly  # noqa: E402
from common import HAND, P, RAW, mass_g  # noqa: E402

OUT_DIR = ROOT / "description"
LINKS = ["base", "turntable", "upper_arm", "forearm", "wrist", "gripper", "finger_a", "finger_b"]
URDF_NAME = {"base": "base_link"}
LIGHT, DARK = "0.91 0.91 0.89 1", "0.16 0.16 0.17 1"
RGBA = {k: LIGHT for k in LINKS} | {"finger_a": DARK, "finger_b": DARK}
# which servo's mass rides on which link (for the inertial data)
SERVO_ON_LINK = {"base": ["J1"], "turntable": ["J2"], "upper_arm": ["J3"], "wrist": ["J4", "J5"], "gripper": ["J6"]}


def link_solids(with_vendor=True):
    """{link: [solids in that link's frame]}. The pinion is drawn as part of the gripper body."""
    out = {k: [] for k in LINKS}
    cache = {}
    for pd, link, loc in assembly.part_instances():
        if pd.name not in cache:
            cache[pd.name] = pd.make()
        out["gripper" if link == "pinion" else link].append(loc * cache[pd.name])
    if with_vendor:
        for _, link, solid in assembly.vendor_instances():
            out[link].append(solid)
    return out


def _inertial(link, solids, printed_mass_g):
    servo_g = sum(RAW["servos"][RAW["joints"][j]["servo"]]["mass_g"] for j in SERVO_ON_LINK.get(link, []))
    mass = max((printed_mass_g + servo_g) / 1000.0, 0.003)
    bb = Compound(solids).bounding_box()
    c = bb.center()
    sx, sy, sz = (max(d, 1.0) / 1000.0 for d in (bb.size.X, bb.size.Y, bb.size.Z))
    # inertia of a solid box of the same size and mass: a rough but safe estimate for simulation
    ixx, iyy, izz = (mass / 12 * (sy ** 2 + sz ** 2), mass / 12 * (sx ** 2 + sz ** 2), mass / 12 * (sx ** 2 + sy ** 2))
    return (f'    <inertial>\n      <origin xyz="{c.X / 1000:.5f} {c.Y / 1000:.5f} {c.Z / 1000:.5f}" rpy="0 0 0"/>\n'
            f'      <mass value="{mass:.4f}"/>\n'
            f'      <inertia ixx="{ixx:.3e}" ixy="0" ixz="0" iyy="{iyy:.3e}" iyz="0" izz="{izz:.3e}"/>\n    </inertial>\n')


def generate(solids=None, printed_mass=None, mesh_tol=0.15) -> Path:
    solids = solids or link_solids()
    if "pinion" in solids:                       # drawn with the gripper body
        solids = dict(solids)
        solids["gripper"] = solids["gripper"] + solids.pop("pinion")
    g, j = P.geometry, RAW["joints"]
    (OUT_DIR / "meshes").mkdir(parents=True, exist_ok=True)
    x = ['<?xml version="1.0"?>',
         "<!-- GENERATED by tools/gen_urdf.py from cad/params/arm_params.json. Do not edit by hand. -->",
         '<robot name="exxeta_arm">']
    for link in LINKS:
        name = URDF_NAME.get(link, link)
        export_stl(Compound(solids[link]), str(OUT_DIR / "meshes" / f"{name}.stl"), tolerance=mesh_tol, angular_tolerance=0.4)
        pm = printed_mass.get(link, 0.0) if printed_mass else sum(mass_g(s) for s in solids[link][:1])
        mesh = f'<mesh filename="meshes/{name}.stl" scale="0.001 0.001 0.001"/>'
        x.append(f'  <link name="{name}">\n{_inertial(link, solids[link], pm)}'
                 f'    <visual>\n      <geometry>{mesh}</geometry>\n'
                 f'      <material name="{name}_mat"><color rgba="{RGBA[link]}"/></material>\n    </visual>\n'
                 f'    <collision>\n      <geometry>{mesh}</geometry>\n    </collision>\n  </link>')
    x.append('  <link name="tcp"/>')

    def servo_limits(jid):
        servo = RAW["servos"][j[jid]["servo"]]
        return servo["stall_torque_kgcm_6v"] * 0.0980665, math.radians(60.0 / servo["speed_s_per_60deg_6v"])

    def revolute(jid, parent, child, xyz, axis):
        d = j[jid]
        effort, vel = servo_limits(jid)
        x.append(f'  <joint name="{d["name"]}" type="revolute">\n'
                 f'    <parent link="{parent}"/>\n    <child link="{child}"/>\n'
                 f'    <origin xyz="{xyz[0] / 1000:.5f} {xyz[1] / 1000:.5f} {xyz[2] / 1000:.5f}" rpy="0 0 0"/>\n'
                 f'    <axis xyz="{axis}"/>\n'
                 f'    <limit lower="{math.radians(d["min_deg"]):.5f}" upper="{math.radians(d["max_deg"]):.5f}" '
                 f'effort="{effort:.3f}" velocity="{vel:.3f}"/>\n  </joint>')

    revolute("J1", "base_link", "turntable", (0, 0, g.shoulder_height_mm), "0 0 1")
    revolute("J2", "turntable", "upper_arm", (g.shoulder_offset_mm, 0, 0), "0 1 0")
    revolute("J3", "upper_arm", "forearm", (0, 0, g.upper_arm_length_mm), "0 1 0")
    revolute("J4", "forearm", "wrist", (0, 0, g.forearm_length_mm), "0 1 0")
    revolute("J5", "wrist", "gripper", (0, 0, 0), "0 0 1")
    # gripper fingers: prismatic, finger_b mirrors finger_a (its frame is turned 180 degrees about Z)
    effort, vel = servo_limits("J6")
    r = HAND.pin_r / 1000.0
    travel = math.radians(j["J6"]["max_deg"]) * r
    lim = f'<limit lower="0" upper="{travel:.5f}" effort="{effort / r:.2f}" velocity="{vel * r:.4f}"/>'
    x.append(f'  <joint name="gripper" type="prismatic">\n    <parent link="gripper"/>\n    <child link="finger_a"/>\n'
             f'    <origin xyz="0 0 0" rpy="0 0 0"/>\n    <axis xyz="1 0 0"/>\n    {lim}\n  </joint>')
    x.append(f'  <joint name="gripper_mimic" type="prismatic">\n    <parent link="gripper"/>\n    <child link="finger_b"/>\n'
             f'    <origin xyz="0 0 0" rpy="0 0 {math.pi:.6f}"/>\n    <axis xyz="1 0 0"/>\n    {lim}\n'
             f'    <mimic joint="gripper" multiplier="1" offset="0"/>\n  </joint>')
    x.append('  <joint name="tcp_fixed" type="fixed">\n    <parent link="gripper"/>\n    <child link="tcp"/>\n'
             f'    <origin xyz="0 0 {g.wrist_to_tcp_mm / 1000:.5f}" rpy="0 0 0"/>\n  </joint>')
    x.append("</robot>\n")
    path = OUT_DIR / "exxeta_arm.urdf"
    path.write_text("\n".join(x), encoding="utf-8")
    info = {"_about": "GENERATED by tools/gen_urdf.py. Facts the software needs besides the URDF.",
            "gripper_m_per_rad": r, "gripper_max_opening_m": 2 * travel,
            "joint_order": [j[k]["name"] for k in ("J1", "J2", "J3", "J4", "J5", "J6")]}
    (OUT_DIR / "robot_info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
    return path


if __name__ == "__main__":
    print("wrote", generate())
