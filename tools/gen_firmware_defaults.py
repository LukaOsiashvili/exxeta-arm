"""Generate firmware/include/arm_defaults.h and the shared protocol test vectors.

Role in the system
------------------
Keeps the firmware in step with the single source of truth:
  * joint limits, default speeds, rest pose and battery thresholds come from
    cad/params/arm_params.json -> firmware/include/arm_defaults.h
  * example frames encoded by the Python protocol code -> tests/protocol_vectors.json
    and firmware/test/test_core/vectors.h, so the C++ decoder is tested against
    exactly the bytes the PC sends (PROJECT_SPEC 7.2 "shared test vectors").

Run after changing the params or the protocol:  python tools/gen_firmware_defaults.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "dora"))

from arm_params import load_params  # noqa: E402
from exxeta_arm import protocol as pr  # noqa: E402

REST_POSE = (0, -72, 120, 85, 0, 0)     # must match cad/assembly.py POSES["rest"]


def defaults_header(p: dict) -> str:
    j = [p["joints"][f"J{i}"] for i in range(1, 7)]
    th = p["power"]["firmware_thresholds"]
    d = p["power"]["battery_sense_divider"]
    arr = lambda vals: "{" + ", ".join(str(v) for v in vals) + "}"  # noqa: E731
    return f"""// GENERATED by tools/gen_firmware_defaults.py from cad/params/arm_params.json. Do not edit.
#pragma once
#include <stdint.h>

static const float DEF_MIN_DEG[6] = {arr(float(x["min_deg"]) for x in j)};
static const float DEF_MAX_DEG[6] = {arr(float(x["max_deg"]) for x in j)};
static const float DEF_MAX_SPEED[6] = {arr(float(x["max_speed_deg_s"]) for x in j)};   // deg/s
static const float DEF_MAX_ACCEL[6] = {arr(float(x["max_accel_deg_s2"]) for x in j)};  // deg/s^2
static const float DEF_REST_POSE[6] = {arr(float(x) for x in REST_POSE)};
// A 180 degree servo is centred at 1500 us. Each joint is assembled so that the servo centre is the MIDDLE of the
// joint range; these are the resulting pulses for joint angle 0 (before individual calibration).
static const uint16_t DEF_ZERO_US[6] = {arr(int(round(1500 - (x["min_deg"] + x["max_deg"]) / 2 * 11.11)) for x in j)};
static const bool DEF_HAS_POT[4] = {arr(str(bool(x["pot"])).lower() for x in j[:4])};

static const float BATT_WARN_V = {th["warn_v"]}f;
static const float BATT_CRITICAL_V = {th["critical_v"]}f;
static const float BATT_HYSTERESIS_V = {th["hysteresis_v"]}f;
static const float BATT_FILTER_TAU_S = {th["filter_time_constant_s"]}f;
static const float BATT_ABSENT_V = {th["servo_power_absent_below_v"]}f;
static const float BATT_CHARGER_V = {th["charger_present_above_v"]}f;
static const float BATT_DIVIDER = {(d["r_top_ohm"] + d["r_bottom_ohm"]) / d["r_bottom_ohm"]:.5f}f;  // pack voltage = pin voltage x this
"""


def vectors() -> list[dict]:
    st = pr.State(mode=2, faults=pr.Fault.BATTERY_WARN, target_deg=[0, -72, 120, 85, 0, 0],
                  position_deg=[1.5, -70.25, 118, 80, -0.5, 10], pot_deg=[1.4, -70, 117.5, 79],
                  pot_valid=0b0110, battery_v=7.412, battery_pct=63, uptime_ms=123456, rx_ok=900, rx_bad=2, last_seq=41)
    frames = [
        ("hello", pr.Frame(pr.Msg.HELLO, 1, pr.hello(0x1234ABCD, 77))),
        ("heartbeat", pr.Frame(pr.Msg.HEARTBEAT, 2)),
        ("enable_with_pots", pr.Frame(pr.Msg.ENABLE, 3, pr.enable(True))),
        ("targets", pr.Frame(pr.Msg.SET_JOINT_TARGETS, 4, pr.set_joint_targets([0, 20, 70, -10.5, 45, 90], [0, 30, 30, 0, 0, 60]))),
        ("stop", pr.Frame(pr.Msg.STOP, 5)),
        ("set_servo_cal_j2", pr.Frame(pr.Msg.SET_CONFIG, 6, pr.set_config(pr.Cfg.SERVO_CAL, 1, pr.servo_cal(520, 2480, 1490, -10.9)))),
        ("jog_pulse", pr.Frame(pr.Msg.CALIBRATION, 7, pr.cal_jog(2, 1600))),
        ("state", pr.Frame(pr.Msg.STATE, 65535, pr.pack_state(st))),
        ("payload_with_zeros", pr.Frame(pr.Msg.LOG, 0, bytes([0, 0, 1, 0, 255, 0]))),
    ]
    out = []
    for name, f in frames:
        raw = pr.encode_frame(f)
        out.append({"name": name, "type": f.type, "seq": f.seq, "payload_hex": f.payload.hex(),
                    "frame_hex": raw.hex(), "cobs_hex": pr.cobs_encode(raw).hex()})
    return out


def vectors_header(vs: list[dict]) -> str:
    def carr(h):
        b = bytes.fromhex(h)
        return "{" + ", ".join(f"0x{x:02X}" for x in b) + "}" if b else "{0}"
    L = ["// GENERATED by tools/gen_firmware_defaults.py from the Python protocol code. Do not edit.", "#pragma once",
         "#include <stddef.h>", "#include <stdint.h>", "",
         "struct Vector { const char* name; uint8_t type; uint16_t seq; const uint8_t* payload; size_t payloadLen;",
         "                const uint8_t* frame; size_t frameLen; const uint8_t* cobs; size_t cobsLen; };", ""]
    for i, v in enumerate(vs):
        L.append(f"static const uint8_t V{i}_P[] = {carr(v['payload_hex'])};")
        L.append(f"static const uint8_t V{i}_F[] = {carr(v['frame_hex'])};")
        L.append(f"static const uint8_t V{i}_C[] = {carr(v['cobs_hex'])};")
    L.append("")
    L.append("static const Vector VECTORS[] = {")
    for i, v in enumerate(vs):
        L.append(f'  {{"{v["name"]}", {v["type"]}, {v["seq"]}, V{i}_P, {len(v["payload_hex"]) // 2}, V{i}_F, '
                 f'{len(v["frame_hex"]) // 2}, V{i}_C, {len(v["cobs_hex"]) // 2}}},')
    L += ["};", f"static const size_t N_VECTORS = {len(vs)};", ""]
    return "\n".join(L)


def main():
    p = load_params()
    (ROOT / "firmware" / "include").mkdir(parents=True, exist_ok=True)
    (ROOT / "firmware" / "include" / "arm_defaults.h").write_text(defaults_header(p), encoding="utf-8")
    vs = vectors()
    (ROOT / "tests").mkdir(exist_ok=True)
    (ROOT / "tests" / "protocol_vectors.json").write_text(json.dumps(
        {"_about": "GENERATED by tools/gen_firmware_defaults.py. Shared by the Python and C++ protocol tests.",
         "protocol_version": pr.VERSION, "vectors": vs}, indent=2), encoding="utf-8")
    (ROOT / "firmware" / "test" / "test_core").mkdir(parents=True, exist_ok=True)
    (ROOT / "firmware" / "test" / "test_core" / "vectors.h").write_text(vectors_header(vs), encoding="utf-8")
    print("wrote arm_defaults.h, protocol_vectors.json, vectors.h")


if __name__ == "__main__":
    main()
